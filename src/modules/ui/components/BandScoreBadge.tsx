export class BandScoreBadgeComponent {
  public static getBadgeGradient(band: number): string {
    if (band >= 8.0) return 'linear-gradient(135deg, #10B981, #059669)';
    if (band >= 7.0) return 'linear-gradient(135deg, #4F46E5, #3730A3)';
    if (band >= 6.0) return 'linear-gradient(135deg, #06B6D4, #0891B2)';
    return 'linear-gradient(135deg, #F59E0B, #D97706)';
  }
}

